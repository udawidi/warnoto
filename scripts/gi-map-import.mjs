#!/usr/bin/env node

/**
 * Prepare the GI coordinate backfill from docs/gi-map-ledger.csv.
 *
 * Default mode only validates the ledger. Use --sql/--sql-file to emit a
 * reviewed SQL transaction, or --rollback-sql to emit the matching rollback.
 * --preflight-sql-file emits only read-only checks inside a rolled-back
 * transaction. All file output is explicitly UTF-8.
 * This script never opens a database connection.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ledgerPath = path.join(root, "docs", "gi-map-ledger.csv");
const args = new Set(process.argv.slice(2));
const batch = process.env.GI_MAP_BATCH || "GI-MAP-LEDGER-VERIFIED-156";

function optionValue(name) {
  const index = process.argv.indexOf(name);
  if (index < 0) return null;
  const value = process.argv[index + 1];
  if (!value || value.startsWith("--")) throw new Error(`${name} membutuhkan path file`);
  return value;
}

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const char = text[i], next = text[i + 1];
    if (char === '"') {
      if (quoted && next === '"') { field += '"'; i += 1; }
      else quoted = !quoted;
    } else if (char === "," && !quoted) { row.push(field); field = ""; }
    else if ((char === "\n" || char === "\r") && !quoted) {
      if (char === "\r" && next === "\n") i += 1;
      if (field || row.length) { row.push(field); rows.push(row); }
      row = []; field = "";
    } else field += char;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [header, ...data] = rows;
  return data.map(values => Object.fromEntries(header.map((key, i) => [key, values[i] || ""])));
}

function sql(value) {
  return `'${String(value ?? "").replaceAll("'", "''")}'`;
}

function loadRows() {
  const rows = parseCsv(fs.readFileSync(ledgerPath, "utf8").replace(/^\uFEFF/, ""));
  const errors = [];
  const ids = new Set();
  const verified = rows.filter(row => row.verification_status.startsWith("verified_"));
  for (const row of verified) {
    const lat = Number(row.lat), lng = Number(row.lng);
    if (!row.gi_id || ids.has(row.gi_id)) errors.push(`${row.gi_id || "<empty>"}: duplicate/empty gi_id`);
    ids.add(row.gi_id);
    if (!Number.isFinite(lat) || lat < -90 || lat > 90) errors.push(`${row.gi_id}: invalid latitude`);
    if (!Number.isFinite(lng) || lng < -180 || lng > 180) errors.push(`${row.gi_id}: invalid longitude`);
    if (!/^https:\/\//i.test(row.exact_map_url)) errors.push(`${row.gi_id}: exact_map_url is not HTTPS`);
    if (!row.exact_map_url.includes(`${row.lat},${row.lng}`)) errors.push(`${row.gi_id}: map URL does not match coordinates`);
  }
  if (errors.length) throw new Error(errors.join("\n"));
  return { rows, verified };
}

function valuesSql(rows) {
  return rows.map(row => `(${[row.gi_id, row.gi_name, row.upt_id, row.ultg_id, row.lat, row.lng, row.exact_map_url, row.provenance_source_url].map(sql).join(", ")})`).join(",\n    ");
}

function rollbackValuesSql(rows) {
  return rows.map(row => `(${[row.gi_id, row.lat, row.lng, row.exact_map_url].map(sql).join(", ")})`).join(",\n    ");
}

function buildSql(rows, { preflightOnly = false } = {}) {
  const values = valuesSql(rows);
  const batchSql = sql(batch);
  const preflight = `-- Generated by scripts/gi-map-import.mjs. Review before execution.\n-- Requires explicit production approval for apply mode.\nBEGIN;\n\nCREATE TEMP TABLE gi_map_import (gi_id text, gi_name text, upt_id text, ultg_id text, lat numeric, lng numeric, map_url text, provenance_url text) ON COMMIT DROP;\nINSERT INTO gi_map_import VALUES\n    ${values};\n\n-- Preflight: every ID/hierarchy/name must match the canonical master.\nSELECT i.gi_id, i.gi_name, g.upt_id, g.ultg_id, g.normalized_name,\n       g.data->>'lat' AS existing_lat, g.data->>'lng' AS existing_lng\nFROM gi_map_import i\nLEFT JOIN public.mtu_khs_gardu_induk g ON g.id = i.gi_id\nWHERE g.id IS NULL\n   OR g.upt_id IS DISTINCT FROM i.upt_id\n   OR g.ultg_id IS DISTINCT FROM i.ultg_id\n   OR upper(btrim(g.normalized_name)) IS DISTINCT FROM upper(btrim(i.gi_name))\n   OR (g.data ? 'lat' AND nullif(g.data->>'lat','') IS DISTINCT FROM i.lat::text)\n   OR (g.data ? 'lng' AND nullif(g.data->>'lng','') IS DISTINCT FROM i.lng::text);\n\nDO $$\nBEGIN\n  IF EXISTS (\n    SELECT 1 FROM gi_map_import i\n    LEFT JOIN public.mtu_khs_gardu_induk g ON g.id = i.gi_id\n    WHERE g.id IS NULL\n       OR g.upt_id IS DISTINCT FROM i.upt_id\n       OR g.ultg_id IS DISTINCT FROM i.ultg_id\n       OR upper(btrim(g.normalized_name)) IS DISTINCT FROM upper(btrim(i.gi_name))\n       OR (g.data ? 'lat' AND nullif(g.data->>'lat','') IS DISTINCT FROM i.lat::text)\n       OR (g.data ? 'lng' AND nullif(g.data->>'lng','') IS DISTINCT FROM i.lng::text)\n  ) THEN RAISE EXCEPTION 'GI_MAP_PREFLIGHT_CONFLICT'; END IF;\nEND $$;\n\n`;
  if (preflightOnly) return `${preflight}ROLLBACK;\n`;
  return `${preflight}-- Existing empty coordinates are filled; identical coordinates are idempotent.\nUPDATE public.mtu_khs_gardu_induk g\nSET data = coalesce(g.data, '{}'::jsonb) || jsonb_build_object(\n  'lat', i.lat, 'lng', i.lng, 'mapSourceUrl', i.map_url,\n  'giMapImport', jsonb_build_object('batch', ${batchSql}, 'provenanceUrl', i.provenance_url, 'status', 'verified_candidate')\n), updated_at = now()\nFROM gi_map_import i\nWHERE g.id = i.gi_id;\n\n-- The GI trigger updates GI-<id> and GILOK-<id> shadow rows in the same transaction.\nCOMMIT;\n`;
}

function emitSql(rows) {
  process.stdout.write(buildSql(rows));
}

function buildRollback(rows) {
  const values = rollbackValuesSql(rows);
  return `-- Generated rollback for batch ${batch}. Review before execution.\n-- Rows edited after import are protected by exact lat/lng/mapSourceUrl predicates.\nBEGIN;\nCREATE TEMP TABLE gi_map_import_rollback (gi_id text, lat text, lng text, map_url text) ON COMMIT DROP;\nINSERT INTO gi_map_import_rollback VALUES\n    ${values};\n\n-- Remove only values still identical to this import batch.\nUPDATE public.mtu_khs_gardu_induk g\nSET data = g.data - 'lat' - 'lng' - 'mapSourceUrl' - 'giMapImport', updated_at = now()\nFROM gi_map_import_rollback i\nWHERE g.id = i.gi_id\n  AND g.data->'giMapImport'->>'batch' = ${sql(batch)}\n  AND g.data->>'lat' = i.lat\n  AND g.data->>'lng' = i.lng\n  AND g.data->>'mapSourceUrl' = i.map_url;\n\n-- Trigger may merge keys into shadows; apply the same edit guard to each shadow.\nUPDATE public.lokasi l\nSET data = l.data - 'lat' - 'lng' - 'mapSourceUrl' - 'giMapImport'\nFROM gi_map_import_rollback i\nWHERE l.id = 'GILOK-' || i.gi_id\n  AND l.data->'giMapImport'->>'batch' = ${sql(batch)}\n  AND l.data->>'lat' = i.lat\n  AND l.data->>'lng' = i.lng\n  AND l.data->>'mapSourceUrl' = i.map_url;\nUPDATE public.gudang g\nSET data = g.data - 'lat' - 'lng' - 'mapSourceUrl' - 'giMapImport'\nFROM gi_map_import_rollback i\nWHERE g.id = 'GI-' || i.gi_id\n  AND g.data->'giMapImport'->>'batch' = ${sql(batch)}\n  AND g.data->>'lat' = i.lat\n  AND g.data->>'lng' = i.lng\n  AND g.data->>'mapSourceUrl' = i.map_url;\nCOMMIT;\n`;
}

function emitRollback(rows) {
  process.stdout.write(buildRollback(rows));
}

try {
  const { rows, verified } = loadRows();
  const statuses = new Map();
  for (const row of rows) statuses.set(row.verification_status, (statuses.get(row.verification_status) || 0) + 1);
  const sqlFile = optionValue("--sql-file");
  const preflightSqlFile = optionValue("--preflight-sql-file");
  const rollbackSqlFile = optionValue("--rollback-sql-file");
  const fileModes = [sqlFile, preflightSqlFile, rollbackSqlFile].filter(Boolean);
  if (fileModes.length > 1) throw new Error("Pilih satu opsi output file SQL");
  if (sqlFile) fs.writeFileSync(path.resolve(process.cwd(), sqlFile), buildSql(verified), "utf8");
  else if (preflightSqlFile) fs.writeFileSync(path.resolve(process.cwd(), preflightSqlFile), buildSql(verified, { preflightOnly: true }), "utf8");
  else if (rollbackSqlFile) fs.writeFileSync(path.resolve(process.cwd(), rollbackSqlFile), buildRollback(verified), "utf8");
  else if (args.has("--sql")) emitSql(verified);
  else if (args.has("--rollback-sql")) emitRollback(verified);
  else if (args.has("--preflight-sql")) process.stdout.write(buildSql(verified, { preflightOnly: true }));
  else {
    console.log(JSON.stringify({ ledgerRows: rows.length, verifiedRows: verified.length, pendingRows: rows.length - verified.length, statuses: Object.fromEntries(statuses), batch }, null, 2));
    console.log("Dry-run only: no database connection and no production write.");
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
